function essence(
  discipline: string,
  key: string,
  name: string,
  description: string,
  ap: number,
  target: CombatTargetSpec,
  effects: readonly CombatEffectDefinition[],
  tags: readonly string[],
): EssenceDefinition {
  const base = skill(discipline, key, ap, target, effects, tags)
  const id = `essence.${discipline}.${key}`
  return {
    essenceId: id,
    contentVersion: 1,
    enabled: true,
    sourceDisciplineId: discipline,
    name,
    description,
    skill: {
      ...base,
      id,
      nameRef: `${id}.name`,
      descriptionRef: `${id}.description`,
      tags: ['essence', ...base.tags.filter((tag) => tag !== 'discipline')],
      cooldown: { key: id, ownerTurns: 4 },
      overrides: { pvp: { apCost: Math.min(100, ap + 5) } },
      media: { iconKey: `${id}.icon`, audioCueKey: `${id}.audio`, vfxKey: `${id}.vfx` },
    },
    authoring: base.authoring,
  }
}
