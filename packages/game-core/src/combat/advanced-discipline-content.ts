const self: CombatTargetSpec = {
  kind: 'self',
  teamPolicy: 'self',
  shape: { kind: 'single' },
  minimumRange: 0,
  maximumRange: 0,
  requiresLineOfSight: false,
  maximumElevationDifference: null,
  friendlyFire: 'allies-only',
}
const melee: CombatTargetSpec = {
  kind: 'unit',
  teamPolicy: 'enemy',
  shape: { kind: 'single' },
  minimumRange: 1,
  maximumRange: 1,
  requiresLineOfSight: false,
  maximumElevationDifference: 1,
  friendlyFire: 'enemies-only',
}
const ranged: CombatTargetSpec = {
  ...melee,
  maximumRange: 4,
  requiresLineOfSight: true,
  maximumElevationDifference: 2,
}
const ally: CombatTargetSpec = {
  ...ranged,
  teamPolicy: 'ally',
  minimumRange: 0,
  friendlyFire: 'allies-only',
  maximumRange: 3,
}
const area = (target: CombatTargetSpec, radius = 1): CombatTargetSpec => ({
  ...target,
  shape: { kind: 'circle', radius },
})
const line = (target: CombatTargetSpec, length = 3): CombatTargetSpec => ({
  ...target,
  maximumRange: length,
  shape: { kind: 'line', length },
})
const damage = (
  amount: number,
  recipient: CombatEffectDefinition['recipient'] = 'primary-unit',
): CombatEffectDefinition => ({ type: 'damage', amount, recipient })
const heal = (
  amount: number,
  recipient: CombatEffectDefinition['recipient'] = 'actor',
): CombatEffectDefinition => ({ type: 'healing', amount, recipient })
const effect = (
  statusId: string,
  recipient: CombatEffectDefinition['recipient'] = 'primary-unit',
): CombatEffectDefinition => ({ type: 'apply-status', statusId, recipient, stacks: 1 })
const mp = (
  delta: number,
  recipient: CombatEffectDefinition['recipient'] = 'actor',
): CombatEffectDefinition => ({ type: 'resource-change', resource: 'mp', delta, recipient })
const cleanse = (
  recipient: CombatEffectDefinition['recipient'] = 'actor',
): CombatEffectDefinition => ({ type: 'remove-status', recipient, statusIds: CLEANSE_STATUS_IDS })
const targetStatus = (statusId: string): CombatUseRequirement[] => [
  { kind: 'target-status-present', statusId },
]
const actorStatus = (statusId: string): CombatUseRequirement[] => [
  { kind: 'actor-status-present', statusId },
]
const lowHp: CombatUseRequirement[] = [{ kind: 'actor-hp-at-most', basisPoints: 5000 }]
function skill(
  discipline: string,
  key: string,
  apCost: number,
  target: CombatTargetSpec,
  effects: readonly CombatEffectDefinition[],
  tags: readonly string[],
  requirements: readonly CombatUseRequirement[] = [],
): MatureSkillDefinition {
  const id = `${discipline}.${key}`
  return {
    id,
    sourceDisciplineId: discipline,
    contentVersion: 1,
    enabled: true,
    nameRef: `skill.${id}.name`,
    descriptionRef: `skill.${id}.description`,
    unlockRequirement: { kind: 'discipline-mastery', minimumStage: 1 },
    apCost,
    mpCost: tags.includes('mystic') ? Math.max(2, Math.floor(apCost / 15)) : 0,
    target,
    effects,
    requirements,
    tags: [
      'discipline',
      discipline,
      ...tags,
      tags.includes('attack')
        ? 'cockpit:attack'
        : tags.includes('heal')
          ? 'cockpit:recovery'
          : 'cockpit:defense',
    ],
    cooldown: { key: id, ownerTurns: 2 },
    ai: { enabled: true, baseUtility: tags.includes('attack') ? 66 : 48, purposeTags: tags },
    overrides: {},
    media: {
      iconKey: `skill.${id}.icon`,
      audioCueKey: `skill.${id}.audio`,
      vfxKey: `skill.${id}.vfx`,
    },
    authoring: {
      schemaVersion: 1,
      status: 'representative',
      validationTags: ['p4', discipline, 'shared-combat-authority'],
    },
  }
}

