export interface PortraitFace {
  id: string
  name: string
  rig: Rig
  painted: boolean
  shape?: 1 | 2
}
function paintedFaces(prefix: string, names: string[], rigs: Rig[]): PortraitFace[] {
  return names.map((name, i) => ({
    id: prefix + String(i + 1).padStart(2, '0'),
    name,
    rig: rigs[i % rigs.length]!,
    painted: true,
  }))
}
