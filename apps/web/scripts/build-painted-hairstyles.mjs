import { writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const [, , source] = process.argv
if (!source) throw new Error('Provide the original four by three hair component sheet.')

const styles = [
  'feather',
  'quiff',
  'curls',
  'crown',
  'layers',
  'bun',
  'topknot',
  'pony',
  'braid',
  'twins',
  'waves',
]
const { width, height } = await sharp(source).metadata()
const columns = [0, 0.276, 0.52, 0.77, 1]
const rows = [0, 0.263, 0.584, 1]
const assets = {}
for (const [index, style] of styles.entries()) {
  const column = index % 4
  const row = Math.floor(index / 4)
  const left = Math.round(width * columns[column])
  const top = Math.round(height * rows[row])
  const region = {
    left,
    top,
    width: Math.round(width * columns[column + 1]) - left,
    height: Math.round(height * rows[row + 1]) - top,
  }
  const raw = { width: region.width, height: region.height, channels: 4 }
  const data = await sharp(source).extract(region).ensureAlpha().raw().toBuffer()
  for (let i = 0; i < data.length; i += 4) {
    const [r, g, b, alpha] = data.subarray(i, i + 4)
    if (alpha < 124 || (r > 170 && r - g > 100 && g < 48 && b < 48)) data[i + 3] = 0
  }
  const result = await sharp(data, { raw })
    .trim({ background: '#00000000', threshold: 72 })
    .resize({ width: 178, height: 184, fit: 'inside' })
    .webp({ quality: 87, alphaQuality: 97 })
    .toBuffer({ resolveWithObject: true })
  assets[style] = {
    uri: `data:image/webp;base64,${result.data.toString('base64')}`,
    width: result.info.width,
    height: result.info.height,
  }
}

await writeFile(
  new URL('../src/appearance/appearance-painted-hairstyles.generated.ts', import.meta.url),
  '// Generated by scripts/build-painted-hairstyles.mjs from the original hair component sheet.\n' +
    `export const PAINTED_HAIRSTYLES = ${JSON.stringify(assets, null, 2)} as const\n`,
)
