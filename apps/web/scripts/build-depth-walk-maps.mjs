// The red and green channels give the source-pixel offsets for SVG's feDisplacementMap.
// Keep the warp continuous across the painted body, outfit, and equipment at the 48×64 rig size.
import { writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const width = 48
const height = 64
const displacementScale = 12
const smooth = (low, high, value) => {
  const t = Math.max(0, Math.min(1, (value - low) / (high - low)))
  return t * t * (3 - 2 * t)
}
const channel = (distance) => Math.round(255 * (0.5 - distance / displacementScale))
const maps = {}
for (const facing of ['north', 'south']) {
  const towards = facing === 'south' ? 1 : -1
  maps[facing] = []
  for (let frame = 0; frame < 8; frame++) {
    const phase = (frame * Math.PI) / 4
    const stride = Math.cos(phase)
    const passing = Math.sin(phase)
    const pixels = Buffer.alloc(width * height * 3)
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width; x++) {
        const side = 1 - 2 * smooth(22.2, 25.8, x + 0.5)
        const hips = smooth(26, 39, y) * (1 - smooth(41, 56, y))
        const shin = smooth(37, 55, y)
        const arm =
          smooth(4, 8, Math.abs(x + 0.5 - 24)) * smooth(24, 33, y) * (1 - smooth(37, 44, y))
        // At contact one boot leads along the ground plane. The other rolls off its toe,
        // clears the ground while passing, and lands on the following half-cycle.
        const swingLift = Math.max(0, -passing * side)
        const ankleTravel = 3.5 * stride * side * towards - 2.15 * swingLift
        const headBob = (0.2 - 0.55 * passing ** 2) * (1 - shin)
        const dx = 0.45 * passing * hips + 0.25 * side * swingLift * shin
        const dy =
          headBob + shin * ankleTravel - arm * (1.55 * stride * side * towards + 0.45 * swingLift)
        const offset = (y * width + x) * 3
        pixels[offset] = channel(dx)
        pixels[offset + 1] = channel(dy)
        pixels[offset + 2] = 128
      }
    }
    const png = await sharp(pixels, { raw: { width, height, channels: 3 } })
      .png()
      .toBuffer()
    maps[facing].push('data:image/png;base64,' + png.toString('base64'))
  }
}
const facingRows = Object.entries(maps)
  .map(
    ([name, images]) =>
      `  ${name}: [\n${images.map((image) => `    '${image}',\n`).join('')}  ],\n`,
  )
  .join('')
await writeFile(
  new URL('../src/appearance/appearance-depth-walk.generated.ts', import.meta.url),
  '// Generated by scripts/build-depth-walk-maps.mjs for the 48×64 appearance rig.\n' +
    `export const DEPTH_WALK_SCALE = ${displacementScale}\n` +
    `export const DEPTH_WALK_MAPS = {\n${facingRows}} as const\n`,
)
