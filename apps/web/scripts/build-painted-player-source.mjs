import { writeFile } from 'node:fs/promises'
import sharp from 'sharp'
import { PAINTED_PRESET_PORTRAITS } from '../src/appearance/appearance-painted-portraits.generated.ts'
import { PAINTED_PRESET_SPRITES } from '../src/appearance/appearance-painted-sprites.generated.ts'

const decode = (uri) => Buffer.from(uri.split(',')[1], 'base64')
const uri = (buffer, format) => `data:image/${format};base64,${buffer.toString('base64')}`
const clamp = (value) => Math.max(0, Math.min(1, value))
const ease = (value) => clamp(value) ** 2 * (3 - 2 * clamp(value))
const size = 256

async function pinePortrait(source) {
  const rgba = await sharp(decode(source)).ensureAlpha().raw().toBuffer()
  const key = new Float32Array(size * size)
  const passable = new Uint8Array(size * size)
  const exterior = new Uint8Array(size * size)
  const queue = []
  for (let i = 0; i < key.length; i++) {
    const x = i % size
    const y = Math.floor(i / size)
    const [r, g] = rgba.subarray(i * 4, i * 4 + 2)
    key[i] = Math.max(clamp((212 - r) / 30), clamp((r - g - 48) / 23))
    passable[i] = Number(
      key[i] < 0.94 && (y < 145 || x < 66 - (y - 145) * 0.56 || x > 170 + (y - 145) * 0.7),
    )
    if (x === 0 || y === 0 || x === size - 1) {
      queue.push(i)
      exterior[i] = 1
    }
  }
  for (let index = 0; index < queue.length; index++) {
    const i = queue[index]
    for (const next of [
      i % size ? i - 1 : -1,
      i % size < size - 1 ? i + 1 : -1,
      i - size,
      i + size,
    ]) {
      if (passable[next] && !exterior[next]) {
        exterior[next] = 1
        queue.push(next)
      }
    }
  }
  const skin = Buffer.alloc(key.length * 2, 255)
  for (let i = 0; i < key.length; i++) {
    const x = i % size
    const y = Math.floor(i / size)
    const [r, g, b] = rgba.subarray(i * 4, i * 4 + 3)
    const hairGaps = (y < 67 || x < 102 || x > 184) && y < 144
    const shoulderGap = y >= 145 && y < 171 && x > 173 + (y - 146) * 1.1
    rgba[i * 4 + 3] =
      exterior[i] || (key[i] < 0.75 && (hairGaps || shoulderGap))
        ? Math.round(key[i] ** 1.26 * 255)
        : 255
    const face = ease((1 - ((x - 145) / 40) ** 2 - ((y - 94) / 62) ** 2) / 0.22)
    const neck = ease((1 - ((x - 146) / 16) ** 2 - ((y - 139) / 28) ** 2) / 0.32)
    const warmth = ease((r - g - 18) / 27) * ease((g - b - 9) / 18)
    skin[i * 2 + 1] = Math.round(
      Math.max(face, neck) * warmth * ease((r - 98) / 45) * rgba[i * 4 + 3],
    )
  }
  return {
    portrait: uri(
      await sharp(rgba, { raw: { width: size, height: size, channels: 4 } })
        .webp({ quality: 91, alphaQuality: 93 })
        .toBuffer(),
      'webp',
    ),
    skin: uri(
      await sharp(skin, { raw: { width: size, height: size, channels: 2 } })
        .png()
        .toBuffer(),
      'png',
    ),
  }
}

const portraits = {}
const skins = {}
for (const [name, source] of Object.entries(PAINTED_PRESET_PORTRAITS[0])) {
  const { portrait, skin } = await pinePortrait(source)
  portraits[name] = portrait
  skins[name] = skin
}

const sprite = await sharp({
  create: { width: 512, height: 176, channels: 4, background: '#00000000' },
})
  .composite(
    PAINTED_PRESET_SPRITES[0].map(({ uri }, index) => ({
      input: decode(uri),
      left: 128 * index + Math.round((128 - [50, 49, 54, 53][index]) / 2),
      top: 14,
    })),
  )
  .png()
  .toBuffer()

const irisAnchors = [
  [67, 28],
  [72, 30],
  [64, 32],
  [54, 29],
]
const spriteRgba = await sharp(sprite).raw().toBuffer()
const fieldSkin = Buffer.alloc(512 * 176 * 2, 255)
for (let y = 0; y < 176; y++) {
  for (let x = 0; x < 512; x++) {
    const i = y * 512 + x
    const [r, g, b, alpha] = spriteRgba.subarray(i * 4, i * 4 + 4)
    const [cx, cy] = irisAnchors[Math.floor(x / 128)]
    const area = ease((1 - (((x % 128) - cx) / 10) ** 2 - ((y - cy - 6) / 14) ** 2) / 0.45)
    fieldSkin[i * 2 + 1] = Math.round(
      area * ease((r - g - 18) / 27) * ease((g - b - 6) / 18) * ease((r - 90) / 50) * alpha,
    )
  }
}
const fieldMask = await sharp(fieldSkin, { raw: { width: 512, height: 176, channels: 2 } })
  .png()
  .toBuffer()

const studioPaper = await sharp(decode(PAINTED_PRESET_PORTRAITS[0].neutral))
  .extract({ left: 209, top: 0, width: 47, height: 151 })
  .resize(256, 256, { fit: 'fill' })
  .webp({ quality: 72 })
  .toBuffer()

await writeFile(
  new URL('../src/appearance/appearance-painted-player.generated.ts', import.meta.url),
  '// Generated by scripts/build-painted-player-source.mjs from original Pine Scout art.\n' +
    `export const PINE_SCOUT_CUTOUTS = ${JSON.stringify(portraits, null, 2)} as const\n\n` +
    `export const PINE_SCOUT_PORTRAIT_SKIN = ${JSON.stringify(skins, null, 2)} as const\n\n` +
    `export const PINE_SCOUT_SPRITE = '${uri(sprite, 'png')}'\n\n` +
    `export const PINE_SCOUT_FIELD_SKIN = '${uri(fieldMask, 'png')}'\n\n` +
    `export const PAINTED_STUDIO_PAPER = '${uri(studioPaper, 'webp')}'\n`,
)
