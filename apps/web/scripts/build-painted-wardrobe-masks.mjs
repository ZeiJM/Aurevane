const smooth = (value, min, max) => Math.max(0, Math.min(1, (value - min) / (max - min)))
const coverage = (x, y, [cx, cy, rx, ry]) =>
  1 - smooth(((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2, 0.67, 1)

async function mask(source, region, field) {
  const {
    data,
    info: { width, height },
  } = await sharp(Buffer.from(source.split(',')[1], 'base64'))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })
  const alpha = Buffer.alloc(width * height * 2, 255)
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const offset = (y * width + x) * 4
      const [r, g, b, a] = data.subarray(offset, offset + 4)
      const face = field
        ? Math.max(...region[Math.floor(x / 128)].map((area) => coverage(x % 128, y, area)))
        : Math.max(...region.map((area) => coverage((x * 176) / width, (y * 176) / height, area)))
      const warmth = smooth(r - g, 9, 20) * smooth(g - b, 5, 15)
      const light = smooth(r, 50, 85)
      alpha[(y * width + x) * 2 + 1] = Math.round(face * warmth * light * a)
    }
  }
  return `data:image/png;base64,${(
    await sharp(alpha, { raw: { width, height, channels: 2 } })
      .png()
      .toBuffer()
  ).toString('base64')}`
}

const fields = {}
const portraits = {}
for (const [id, source] of Object.entries(PAINTED_ACTORS)) {
  fields[id] = await mask(
    source,
    fieldRegions[id].map((head, facing) => [head, ...fieldHands[id][facing]]),
    true,
  )
  portraits[id] = {}
  for (const [expression, portrait] of Object.entries(PAINTED_ACTOR_PORTRAITS[id])) {
    portraits[id][expression] = await mask(portrait, portraitRegions[id], false)
  }
}
