// Register the straight-on artwork to the same scalp, shoulders and soles as the
// other facings. Work at twice the rig's native scale for battle zoom.
import { readFile, writeFile } from 'node:fs/promises'
import { format } from 'prettier'
import sharp from 'sharp'

const source = await readFile(
  new URL(
    '../../../content/art-requests/sources/appearance/south-facing-characters.webp',
    import.meta.url,
  ),
)
const identities = ['scout', 'ranger', 'guard', 'elder', 'pinescout', 'winterguard', 'emberenvoy']
const tops = [20, 16, 12, 17, 14, 14, 14]
const uri = (bytes) => 'data:image/png;base64,' + bytes.toString('base64')
const actors = {}
for (const [index, id] of identities.entries()) {
  const top = tops[index]
  const height = 159 - top
  const raw = await sharp(source)
    .extract({ left: (index % 4) * 375, top: index < 4 ? 0 : 524, width: 375, height: 524 })
    .png()
    .toBuffer()
  const { data: crop, info } = await sharp(raw)
    .trim({ threshold: 12 })
    .resize({ height: height * 2 })
    .png()
    .toBuffer({ resolveWithObject: true })
  const registered = await sharp({
    create: { width: 256, height: 352, channels: 4, background: '#00000000' },
  })
    .composite([{ input: crop, left: Math.round((256 - info.width) / 2), top: top * 2 }])
    .png()
    .toBuffer()
  actors[id] = {
    top,
    height,
    body: uri(await sharp(registered).png({ palette: true, quality: 100 }).toBuffer()),
  }
  if (index >= 5) continue
  const { data } = await sharp(registered)
    .resize(128, 176)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })
  const mask = Buffer.alloc(128 * 176 * 2, 255)
  // Skin excludes shirts, leather and hair. The bare face, neck, and hands have
  // separate registered regions so complexion changes stay on the character.
  const eyeY = top + Math.round(height * [0.144, 0.116, 0.092, 0.105, 0.127][index])
  const halfFace = [8, 7.5, 8, 8, 7.5][index]
  for (let y = 0; y < 176; y++)
    for (let x = 0; x < 128; x++) {
      const i = y * 128 + x
      const [r, g, b, a] = data.subarray(4 * i, 4 * i + 4)
      const face = ((x - 64) / halfFace) ** 2 + ((y - eyeY - 2.3) / 9.4) ** 2
      const neck = ((x - 64) / 4.6) ** 2 + ((y - eyeY - 10.8) / 5.9) ** 2
      const outerHand =
        (id === 'guard' || id === 'ranger' || id === 'elder') &&
        Math.abs(x - 64) > 15 &&
        y > top + height * 0.49 &&
        y < top + height * 0.65
      const warm =
        Math.max(0, Math.min(1, (r - g - 4) / 17)) * Math.max(0, Math.min(1, (g - b - 2) / 9))
      mask[i * 2 + 1] = Math.round(
        a * warm * Math.max(0, Math.min(1, (1 - Math.min(face, neck)) * 5 + 0.2, 1)),
      )
      if (outerHand) mask[i * 2 + 1] = Math.round(a * warm)
    }
  actors[id].skin = uri(
    await sharp(mask, { raw: { width: 128, height: 176, channels: 2 } })
      .png()
      .toBuffer(),
  )
}
const output =
  '// Generated by scripts/build-frontal-actors.mjs from the original Aurevane frontal master.\n' +
  'export const FRONTAL_ACTORS = ' +
  JSON.stringify(actors, null, 2) +
  ' as const\n'
await writeFile(
  new URL('../src/appearance/appearance-frontal.generated.ts', import.meta.url),
  await format(output, { parser: 'typescript', singleQuote: true, semi: false, printWidth: 100 }),
)
