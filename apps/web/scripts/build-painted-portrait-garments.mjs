import { writeFile } from 'node:fs/promises'
import sharp from 'sharp'

const [, , source] = process.argv
if (!source) throw new Error('Provide the 3 by 3 portrait garment sheet.')

const garments = [
  'compass',
  'pine',
  'hawkmantle',
  'shearling',
  'scarf',
  'brigandine',
  'brocade',
  'hooded',
  'quilted',
]
const { width, height } = await sharp(source).metadata()
const assets = {}
for (const [index, style] of garments.entries()) {
  const column = index % 3
  const row = Math.floor(index / 3)
  const left = Math.floor((width * column) / 3)
  const top = Math.floor((height * row) / 3)
  const crop = {
    left,
    top,
    width: Math.floor((width * (column + 1)) / 3) - left,
    height: Math.floor((height * (row + 1)) / 3) - top,
  }
  const data = await sharp(source).extract(crop).ensureAlpha().raw().toBuffer()
  let x0 = crop.width
  let y0 = crop.height
  let x1 = 0
  let y1 = 0
  for (let pixel = 0; pixel < data.length; pixel += 4) {
    const alpha = data[pixel + 3]
    if (alpha < 70) {
      data[pixel + 3] = 0
      continue
    }
    const x = (pixel / 4) % crop.width
    const y = Math.floor(pixel / 4 / crop.width)
    x0 = Math.min(x, x0)
    y0 = Math.min(y, y0)
    x1 = Math.max(x, x1)
    y1 = Math.max(y, y1)
  }
  const { data: encoded, info } = await sharp(data, {
    raw: { width: crop.width, height: crop.height, channels: 4 },
  })
    .extract({ left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 })
    .resize({ width: 278 })
    .webp({ quality: 88, alphaQuality: 95 })
    .toBuffer({ resolveWithObject: true })
  assets[style] = {
    uri: `data:image/webp;base64,${encoded.toString('base64')}`,
    height: info.height,
  }
}

await writeFile(
  new URL('../src/appearance/appearance-painted-portrait-garments.generated.ts', import.meta.url),
  '// Generated by scripts/build-painted-portrait-garments.mjs from the original portrait wardrobe sheet.\n' +
    `export const PAINTED_PORTRAIT_GARMENTS = ${JSON.stringify(assets, null, 2)} as const\n`,
)
