create or replace function public.send_pvp_battle_chat_v1(
  p_user_id uuid,
  p_battle_session_id uuid,
  p_body text
)
returns table (
  message_id bigint,
  sender_character_id uuid,
  sender_character_name text,
  body text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = pg_catalog, public, app_private
as $$
declare
  v_character_id uuid;
  v_body text;
  v_message_id bigint;
begin
  v_body := btrim(coalesce(p_body, ''));
  if char_length(v_body) < 1 or char_length(v_body) > 280 then
    raise exception 'PVP_CHAT_INVALID' using errcode = '22023';
  end if;

  select bp.character_id
    into v_character_id
  from app_private.battle_participants bp
  join app_private.battle_sessions b on b.id = bp.battle_session_id
  where bp.battle_session_id = p_battle_session_id
    and bp.user_id = p_user_id
    and bp.character_id is not null
    and b.lifecycle = 'active'
  limit 1;

  if v_character_id is null then
    raise exception 'PVP_CHAT_FORBIDDEN' using errcode = '42501';
  end if;

  insert into app_private.pvp_battle_chat_messages (
    battle_session_id,
    sender_user_id,
    sender_character_id,
    body
  ) values (
    p_battle_session_id,
    p_user_id,
    v_character_id,
    v_body
  ) returning id into v_message_id;

  return query
  select m.id, m.sender_character_id, c.name, m.body, m.created_at
  from app_private.pvp_battle_chat_messages m
  join public.characters c on c.id = m.sender_character_id
  where m.id = v_message_id;
end;
$$;

create or replace function public.list_pvp_battle_events_v1(
  p_user_id uuid,
  p_battle_session_id uuid,
  p_limit integer default 100
)
returns table (
  battle_version bigint,
  event_index integer,
  event jsonb,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = pg_catalog, public, app_private
as $$
declare
  v_authorized boolean;
  v_limit integer := greatest(1, least(coalesce(p_limit, 100), 100));
begin
  select (
    exists (
      select 1 from app_private.battle_participants bp
      where bp.battle_session_id = p_battle_session_id and bp.user_id = p_user_id
    )
    or exists (
      select 1 from app_private.pvp_active_spectating s
      where s.battle_session_id = p_battle_session_id and s.user_id = p_user_id
    )
  ) into v_authorized;

  if not v_authorized then
    raise exception 'PVP_BATTLE_FORBIDDEN' using errcode = '42501';
  end if;

  return query
  select recent.battle_version, recent.event_index, recent.event, recent.created_at
  from (
    select e.battle_version, e.event_index, e.event, e.created_at
    from app_private.battle_events e
    where e.battle_session_id = p_battle_session_id
    order by e.battle_version desc, e.event_index desc
    limit v_limit
  ) recent
  order by recent.battle_version asc, recent.event_index asc;
end;
$$;

